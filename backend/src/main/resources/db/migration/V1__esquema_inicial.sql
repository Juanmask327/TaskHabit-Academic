-- ------------------------------------------------------------------ USUARIOS
CREATE TABLE usuarios (
    -- Llave primaria autoincremental: PostgreSQL asigna 1, 2, 3... en cada INSERT.
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- uid que Firebase le da a cada cuenta. UNIQUE: un usuario de Firebase = una fila.
    firebase_uid    VARCHAR(128) NOT NULL UNIQUE,
    correo          VARCHAR(255) NOT NULL,
    nombre          VARCHAR(120) NOT NULL,
    -- CHECK: la BD misma rechaza cualquier rol distinto a estos dos.
    rol             VARCHAR(20)  NOT NULL CHECK (rol IN ('DOCENTE', 'ESTUDIANTE')),
    -- Borrado lógico: en vez de DELETE se marca activo = FALSE (se conserva el historial).
    activo          BOOLEAN      NOT NULL DEFAULT TRUE,
    fecha_registro  TIMESTAMP WITH TIME ZONE NOT NULL
);

-- ------------------------------------------------------------------ TAREAS
CREATE TABLE tareas (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Llave foránea: cada tarea pertenece a un usuario. ON DELETE CASCADE = si se borra el
    -- usuario (físicamente), se borran sus tareas; así no quedan filas "huérfanas".
    usuario_id           BIGINT       NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    titulo               VARCHAR(150) NOT NULL,
    descripcion          VARCHAR(1000),
    tipo                 VARCHAR(10)  NOT NULL CHECK (tipo IN ('TAREA', 'HABITO')),
    prioridad            VARCHAR(10)  NOT NULL CHECK (prioridad IN ('BAJA', 'MEDIA', 'ALTA')),
    completada           BOOLEAN      NOT NULL DEFAULT FALSE,
    -- Opcional (NULL permitido): fecha límite, servirá para los recordatorios.
    fecha_entrega        TIMESTAMP WITH TIME ZONE,
    fecha_creacion       TIMESTAMP WITH TIME ZONE NOT NULL,
    -- Se actualiza en cada UPDATE; la sincronización offline la usará para saber qué cambió.
    fecha_actualizacion  TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Índice: casi todas las consultas filtran "WHERE usuario_id = ?". Sin índice PostgreSQL
-- recorrería la tabla completa; con él va directo a las filas de ese usuario.
CREATE INDEX idx_tareas_usuario ON tareas (usuario_id);

-- ------------------------------------------------------------------ REPORTES
CREATE TABLE reportes (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    autor_id                 BIGINT       NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    titulo                   VARCHAR(150) NOT NULL,
    fecha_inicio             DATE         NOT NULL,
    fecha_fin                DATE         NOT NULL,
    -- Totales calculados a partir de la tabla tareas al generar/actualizar el reporte.
    total_tareas             INTEGER      NOT NULL,
    tareas_completadas       INTEGER      NOT NULL,
    total_habitos            INTEGER      NOT NULL,
    habitos_completados      INTEGER      NOT NULL,
    -- NUMERIC(5,2): hasta 999.99 con 2 decimales exactos (ej. 87.50 %).
    porcentaje_cumplimiento  NUMERIC(5, 2) NOT NULL,
    observaciones            VARCHAR(1000),
    fecha_generacion         TIMESTAMP WITH TIME ZONE NOT NULL,
    -- Regla de negocio protegida por la propia BD: el periodo no puede ir "hacia atrás".
    CONSTRAINT chk_reportes_periodo CHECK (fecha_fin >= fecha_inicio)
);

CREATE INDEX idx_reportes_autor ON reportes (autor_id);
